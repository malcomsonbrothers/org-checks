#!/usr/bin/env bash
# Tests for check-crate-tokens.py and the copy embedded in its workflow. Each case runs in a
# throwaway git repo. Needs uv (it installs the pinned tiktoken). Usage:
#   scripts/check-crate-tokens.test.sh
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1 GIT_AUTHOR_NAME=t GIT_COMMITTER_NAME=t \
  GIT_AUTHOR_EMAIL=t@example.com GIT_COMMITTER_EMAIL=t@example.com
unset CRATE_TOKENS_EXCEPTION CRATE_TOKENS_DEFAULT_BRANCH
passed=0 failed=0

repo() { # fresh repo on master with one commit
  cd "$work" && rm -rf "$1" && git init -q -b master "$1" && cd "$1"
  printf 'x\n' > README.md && save init
}
crate() { mkdir -p "$1" && printf '[package]\nname = "%s"\n' "${1##*/}" > "$1/Cargo.toml"; }
pkg() { mkdir -p "$1" && printf '{ "name": "%s" }\n' "${1##*/}" > "$1/package.json"; }
big() { mkdir -p "$(dirname "$1")" && seq 1 "${2:-40000}" > "$1"; } # well over 50k tokens
small() { mkdir -p "$(dirname "$1")" && printf 'fn main() {}\n' > "$1"; }
cfg() { printf '%s\n' "$@" > .crate-tokens; }
save() { git add -A && git commit -q --no-verify -m "${1:-c}"; }
run() { out=$("$@" 2>&1) && rc=0 || rc=$?; }
check() { run uv run --no-config --quiet --script "$here/scripts/check-crate-tokens.py" "$@"; }
units() { check --report; printf '%s\n' "$out" | awk 'NR > 1 { print $3 }' | sort | tr '\n' ' '; }
tokens() { check --report; printf '%s\n' "$out" | awk -v u="$1" '$3 == u { print $1 }'; }
expect() { # expect NAME RC [PATTERN that must appear in the output]
  if [ "$rc" = "$2" ] && { [ -z "${3:-}" ] || printf '%s\n' "$out" | grep -q -e "$3"; }; then
    passed=$((passed + 1))
  else
    failed=$((failed + 1)); echo "not ok: $1 (exit $rc, wanted $2${3:+, /$3/})"; printf '%s\n' "$out" | sed 's/^/    /'
  fi
}
same() { # same NAME GOT WANT
  if [ "$2" = "$3" ]; then passed=$((passed + 1)); else
    failed=$((failed + 1)); echo "not ok: $1"; echo "    got:  $2"; echo "    want: $3"
  fi
}

# Discovery: Cargo packages and JS/TS packages, not workspace roots, node_modules or build output.
repo discover
printf '[workspace]\nmembers = ["crates/*"]\n' > Cargo.toml
crate crates/a; small crates/a/src/lib.rs
mkdir -p crates/b && printf '[workspace]\n\n[package] # the root crate\nname = "b"\n' > crates/b/Cargo.toml
printf '{ "private": true, "workspaces": ["web/*"] }\n' > package.json
pkg web/app; pkg web/app/node_modules/dep; pkg web/app/dist/out
pkg pnpm-root && printf 'packages: ["*"]\n' > pnpm-root/pnpm-workspace.yaml
mkdir -p notes && printf 'not a unit\n' > notes/a.md
save
same "discovers packages only" "$(units)" "crates/a crates/b web/app "
printf '[package]  # crlf\r\nname = "c"\r\n' > Cargo.toml; mkdir -p crlf && printf '[package]\r\nname = "d"\r\n' > crlf/Cargo.toml
same "CRLF manifests are packages" "$(units)" ". crates/a crates/b crlf web/app "
check; expect "small units pass" 0 'checked, each within its budget'

# Control characters in a unit path are escaped, so they cannot inject "::" workflow commands;
# non-UTF-8 paths do not crash the check.
repo hostile; evil=$'evil\n::error title=x::injected'; crate "$evil"; big "$evil/src/lib.rs"
crate $'raw\xff'; small $'raw\xff/src/lib.rs'; save
check; expect "control characters are escaped" 1 '^\[FAIL\] evil\\x0a::error title=x::injected: [0-9]* tokens'
printf '%s\n' "$out" | grep -q '^::' && expect "no output line starts a workflow command" x
check --report; expect "a non-UTF-8 path does not crash" 0 'raw\\udcff$'

# A repository whose root is a package is the unit ".", and nested units own their files.
repo nested; pkg .; crate tools/gen; big tools/gen/src/main.rs; small src/index.ts; save
same "root and nested units" "$(units)" ". tools/gen "
check; expect "nested unit over the limit" 1 '\[FAIL\] tools/gen: [0-9]* tokens, limit 50000 (split it)'
printf '%s\n' "$out" | grep -q '\[FAIL\] \.:' && expect "root does not count the nested unit" x

# Generated files, build output, lockfiles and exempt globs are not counted.
repo skips; crate core; small core/src/lib.rs; save
base=$(tokens core)
big core/Cargo.lock; big core/src/schema.d.ts; big core/dist/bundle.js; big core/.sqlx/q.json
big core/openapi/api.json; big core/openapi.json; big core/swagger-v2.yaml; big core/target/debug/x.rs; big core/icons/logo.svg
{ echo '// @generated by a tool'; seq 1 40000; } > core/src/gen.rs
{ echo '// Code generated by protoc. DO NOT EDIT.'; seq 1 40000; } > core/src/pb.rs
mkdir -p core/node_modules && big core/node_modules/x.js
printf '\0binary' > core/blob.bin; ln -s src/lib.rs core/link.rs
save; same "skipped files add nothing" "$(tokens core)" "$base"
check; expect "skipped files pass" 0
big core/vendor/huge.rs; check; expect "vendored file counts" 1 '\[FAIL\] core:'
cfg 'exempt core/vendor/**'; check; expect "exempt glob" 0
cfg 'exempt core/*/huge.rs'; check; expect "exempt glob, one segment" 0
cfg 'exempt *.rs'; check; expect "* does not cross /" 1 '\[FAIL\] core:'
cfg 'exempt **/huge.rs'; check; expect "**/ matches any depth" 0
git ls-files --others --exclude-standard | grep -q vendor || expect "untracked files are counted" x

# Baseline rows grandfather a unit at its count.
repo baseline; crate big; big big/src/lib.rs; save
check; expect "over the limit without a row" 1 'big: [0-9]* tokens, limit 50000'
n=$(tokens big)
cfg "baseline big $n"; check; expect "row holds at the count" 0
cfg "baseline big/ $n"; check; expect "trailing slash is the same unit" 0
cfg "baseline big $((n - 1))"; check; expect "grew past the row" 1 "big: $n tokens, baseline $((n - 1)) (grew"
cfg "baseline big $((n + 5))"; check; expect "shrank: a note, not a failure" 0 "lower its row to \"baseline big $n\""
cfg "baseline big $n" "baseline gone 60000"; check; expect "stale row: a note" 0 'row for gone matches no unit'
cfg "baseline big $n" "baseline big $n"; check; expect "duplicate rows fail" 1 'duplicate baseline row for big'
cfg 'baselines big 1'; check; expect "unknown directive fails" 1 'unknown or malformed line'
cfg 'baseline big many'; check; expect "non-numeric row fails" 1 'unknown or malformed line'
big big/src/lib.rs 3000; cfg "baseline big $n"; check; expect "within the limit: a note" 0 'delete its .crate-tokens row'

# --ci: .crate-tokens may only shrink against the base, unless the label allows it.
repo ci; crate big; big big/src/lib.rs; save
n=$(tokens big)
cfg "baseline big $n"; save rows
check --ci HEAD~1; expect "new row fails in CI" 1 "^\[FAIL\] .crate-tokens: new baseline row big $n$"
printf '%s\n' "$out" | grep -q 'crate-tokens-exception label' || expect "failure names the label" x
CRATE_TOKENS_EXCEPTION=true check --ci HEAD~1; expect "the label allows a new row" 0 'allowed by the crate-tokens-exception label'
check --ci HEAD; expect "unchanged rows pass" 0
cfg "baseline big $((n + 9))"; save raise
check --ci HEAD~1; expect "raised row fails" 1 "baseline row big raised from $n to $((n + 9))"
cfg "baseline big $n" 'exempt big/gen/**'; save exempt
check --ci HEAD~1; expect "new exempt line fails" 1 'new exempt line big/gen/\*\*'
cfg "baseline big $n"; save drop
check --ci HEAD~1; expect "dropping an exempt line passes" 0
check --ci 0000000000000000000000000000000000000000; expect "zero base, no default branch" 1 'new baseline row'
git branch -q base HEAD~1; CRATE_TOKENS_DEFAULT_BRANCH=base check --ci 0000000000000000000000000000000000000000
expect "zero base falls back to the default branch" 0
git rm -q .crate-tokens; save
check --ci HEAD~1; expect "deleting .crate-tokens does not skip" 1 '\[FAIL\] big:'

# Each projects/<p>/.crate-tokens adds rows relative to its folder ("." is the folder).
pcfg() { local d=$1; shift; mkdir -p "projects/$d"; printf '%s\n' "$@" > "projects/$d/.crate-tokens"; }
repo mono; crate projects/a; big projects/a/src/lib.rs; crate projects/a/core; big projects/a/core/src/lib.rs
crate projects/b; big projects/b/src/lib.rs; save
na=$(tokens projects/a); nc=$(tokens projects/a/core); nb=$(tokens projects/b)
pcfg a "baseline . $na" "baseline core $nc"; check; expect "a folder's rows cover only its folder" 1 "^\[FAIL\] projects/b: $nb tokens, limit"
printf '%s\n' "$out" | grep -q 'FAIL\] projects/a' && expect "\".\" and relative units in a folder file" x
pcfg b "baseline . $nb"; save cfgs; check; expect "every folder's config is read" 0
cfg "baseline projects/b $nb"; check; expect "a unit in two files is a duplicate" 1 'projects/b/.crate-tokens: duplicate baseline row for projects/b'
rm .crate-tokens projects/b/.crate-tokens; pcfg a 'exempt **'; mkdir -p other; printf 'exempt **\n' | tee other/.crate-tokens > projects/b/src/.crate-tokens
check; expect "a folder glob stops at its folder, deeper files are not configs" 1 '^\[FAIL\] projects/b:'
git checkout -q -- projects && rm -rf other projects/b/src/.crate-tokens
pcfg a "baseline . $na" "baseline core $nc" "baseline gone 60000"; check; expect "notes name the folder file" 0 'projects/a/.crate-tokens row for projects/a/gone matches no unit'
pcfg a "baseline . $na" "baseline core $nc" 'exempt gen/**'; save
check --ci HEAD~1; expect "each folder file may only shrink" 1 '^\[FAIL\] projects/a/.crate-tokens: new exempt line gen/\*\*$'
CRATE_TOKENS_EXCEPTION=true check --ci HEAD~1; expect "the label allows a folder line" 0 'label: new exempt line gen/\*\*$'
pcfg a "baseline . $((na + 5))" "baseline core $nc"; save
check --ci HEAD~1; expect "a raised folder row" 1 "^\[FAIL\] projects/a/.crate-tokens: baseline row projects/a raised from $na to $((na + 5))$"
pcfg a "baseline core $nc"; cfg "baseline projects/a $na"; save
check --ci HEAD~1; expect "moving a row to the root is new there" 1 "^\[FAIL\] .crate-tokens: new baseline row projects/a $na$"

repo dotdir; crate projects/.hid; big projects/.hid/src/lib.rs; save; n=$(tokens projects/.hid)
pcfg .hid "baseline . $n"; check; expect "a dot-folder config is not read" 1 '^\[FAIL\] projects/.hid: '

# --print-baseline prints a row for every unit over the limit at its count; appending them passes.
repo adopt; crate a; big a/src/lib.rs; pkg web; big web/src/app.ts; crate ok; small ok/src/lib.rs; save
check --print-baseline; expect "print-baseline exits 0" 0
same "print-baseline rows" "$(printf '%s\n' "$out" | awk '{ print $1, $2 }' | tr '\n' ' ')" "baseline a baseline web "
uv run --no-config --quiet --script "$here/scripts/check-crate-tokens.py" --print-baseline >> .crate-tokens
check; expect "appending the rows makes the tree pass" 0
git rm -q --cached .crate-tokens >/dev/null 2>&1 || :; rm .crate-tokens
check; expect "failure output names the one-liner" 1 'scripts/check-crate-tokens.sh |$'
printf '%s\n' "$out" | grep -q 'needs the crate-tokens-exception label' || expect "failure output names the label" x
run env CRATE_TOKENS_ENGINE="$here/scripts/check-crate-tokens.py" bash -s -- --print-baseline \
  < "$here/scripts/check-crate-tokens.sh"
expect "the wrapper works piped into bash" 0 '^baseline a [0-9]*$'
run "$here/scripts/check-crate-tokens.sh" --report; expect "the wrapper runs the engine beside it" 0 'tokens  files  unit'
cfg 'nonsense'; check --print-baseline; expect "config errors fail print-baseline" 1 'unknown or malformed'
cfg; check --report; expect "report lists units" 0 '^  tokens  files  unit$'
check --bogus; expect "unknown mode" 2 usage

# Every required check uses the self-hosted metal pool for every repository visibility.
metal='    runs-on: [self-hosted, Linux, metal]'

# The workflow runs on pull requests, on that runner, and embeds this exact engine.
wf="$here/.github/workflows/crate-tokens.yml"
run grep -n -E '^  pull_request:$|--ci "\$PR_BASE"' "$wf"
[ "$(printf '%s\n' "$out" | wc -l | tr -d ' ')" = 2 ] && rc=0 || rc=1
expect "workflow: pull_request trigger, --ci against the base" 0
run grep -n -E 'runs-on:' "$wf"; [ -n "$out" ] && [ "$out" = "$(grep -n -x -F "$metal" "$wf")" ] && rc=0 || rc=1
expect "one runner: self-hosted metal for every repository visibility" 0
run grep -n -E 'uses: [^ ]*@[^ ]*$' "$wf"; expect "every action is pinned with a version comment" 1
run awk '/<<.ENGINE.$/ { on = 1; next } /^ *ENGINE$/ { on = 0 } on { sub(/^          /, ""); print }' "$wf"
[ "$out" = "$(cat "$here/scripts/check-crate-tokens.py")" ] && rc=0 || rc=1
expect "workflow copy matches scripts/check-crate-tokens.py (re-embed it)" 0

echo "crate-tokens tests: $passed passed, $failed failed"
[ "$failed" -eq 0 ]
